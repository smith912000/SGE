const SIGN_CARD = { Aries: 'Ari', Taurus: 'Tau', Gemini: 'Gem', Cancer: 'Cnc', Leo: 'Leo', Virgo: 'Vir', Libra: 'Lib', Scorpio: 'Sco', Sagittarius: 'Sgr', Capricorn: 'Cap', Aquarius: 'Aqr', Pisces: 'Psc' };
const AST_CARD = { Ori: 'Ori', Tau: 'Tau', Peg: 'Peg' };

// The picture for a symbol, or null when the traditions left none we can show.
export function plateFor(ent) {
  if (!ent) return null;
  const card = (k) => PLATES[`card:${k}`] || null;
  switch (ent.kind) {
    case 'planet': case 'sym': case 'branch': return PLATES[ent.id] || null;
    case 'sign': return card(SIGN_CARD[ent.name]);
    case 'const': case 'fig': return card(ent.fig);
    case 'ast': return ent.name === 'Summer Triangle' ? card('Cyg') : card(AST_CARD[ent.fig]);
    default: return null;
  }
}
